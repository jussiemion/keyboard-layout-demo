import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Bound each source file independently of the number of translations per symbol.
export function writeSymbolData(directory, records, groupFor = () => 'names') {
  const root = new URL(`../lib/${directory}/`, import.meta.url);
  mkdirSync(root, { recursive: true });
  const groups = new Map();
  for (const [symbol, value] of Object.entries(records)) {
    const group = groupFor(value);
    const entries = groups.get(group) ?? [];
    entries.push([symbol, value]);
    groups.set(group, entries);
  }
  const files = [];
  for (const [group, entries] of groups) {
    let chunk = {};
    let bytes = 0;
    let part = 0;
    const flush = () => {
      if (!Object.keys(chunk).length) {
        return;
      }
      const name = `${group}-${String(++part).padStart(3, '0')}.json`;
      writeFileSync(new URL(name, root), JSON.stringify(chunk, null, 2) + '\n');
      writeFileSync(
        new URL(name.replace('.json', '.ts'), root),
        `// Generated data adapter for Node and Vite.\nimport data from './${name}' with { type: 'json' };\nexport default data;\n`,
      );
      files.push(name);
      chunk = {};
      bytes = 0;
    };
    for (const [symbol, value] of entries) {
      const size = Buffer.byteLength(
        JSON.stringify({ [symbol]: value }, null, 2),
      );
      if (bytes + size > 128 * 1024) {
        flush();
      }
      chunk[symbol] = value;
      bytes += size;
    }
    flush();
  }
  writeFileSync(
    new URL('manifest.json', root),
    JSON.stringify(files, null, 2) + '\n',
  );
  const loaders = files
    .map((file) => `  () => import('./${file.replace('.json', '.ts')}'),`)
    .join('\n');
  writeFileSync(
    new URL('index.ts', root),
    `// Generated by tools/symbol-data-files.mjs.\nconst loaders = [\n${loaders}\n];\n\nexport async function loadData(): Promise<Record<string, unknown>> {\n  const parts = await Promise.all(loaders.map((load) => load()));\n  const result: Record<string, unknown> = {};\n  for (const part of parts) {\n    Object.assign(result, part.default);\n  }\n  return result;\n}\n`,
  );
  console.log(`${fileURLToPath(root)}: ${files.length} data files`);
}
